test('--baseline clears drift for exactly the named skill', () => {
  const f = fixture(); f.modes({ bro: 'native', other: 'native' });
  for (const name of ['bro', 'other']) { f.write(`.claude/skills/${name}/SKILL.md`, body(name)); f.write(`.agents/skills/${name}/SKILL.md`, body(name)); }
  f.baseline('bro', 'other');
  const before = JSON.parse(f.read('.agents/skill-sources.json')).skills;
  for (const name of ['bro', 'other']) f.write(`.claude/skills/${name}/SKILL.md`, body(name).replace('Explain', 'Changed'));
  f.baseline('bro');
  const after = JSON.parse(f.read('.agents/skill-sources.json')).skills;
  assert.notEqual(after.bro, before.bro);
  assert.equal(after.other, before.other);
  assert.deepEqual(Object.keys(after), ['bro', 'other']);
  assert.ok(f.read('.agents/skill-sources.json').endsWith('}\n'));
  const result = f.run();
  assert.notEqual(result.status, 0);
  assert.doesNotMatch(result.stderr, /bro: the Claude skill changed/);
  assert.match(result.stderr, /other: the Claude skill changed/);
});

test('--baseline rejects uncovered and unknown names and records nothing', () => {
  const f = fixture(); f.modes({ bro: 'native', extra: 'native', off: 'disabled' });
  for (const name of ['bro', 'extra']) f.write(`.agents/skills/${name}/SKILL.md`, body(name));
  f.write('.claude/skills/off/SKILL.md', body('off'));
  for (const name of ['extra', 'off', 'unknown']) {
    const result = f.run('--baseline', 'bro', name);
    assert.notEqual(result.status, 0, name);
    assert.match(result.stderr, new RegExp(`${name} is not a native Codex skill`));
    assert.equal(fs.existsSync(path.join(f.root, '.agents/skill-sources.json')), false, name);
  }
  assert.notEqual(f.run('--baseline').status, 0);
});

